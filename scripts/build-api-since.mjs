#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { exportsOf } from "./api-exports.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CORE = join(ROOT, "packages", "xtyle");
const OUT = join(CORE, "api-since.json");
const MEMBERS_OUT = join(CORE, "src", "manifest", "members-since.generated.ts");

/** The manifest fields whose entries arrive one at a time, and how an entry is named. */
const MEMBER_FIELDS = ["props", "events", "methods", "variants", "sizes", "states", "slots", "anatomy", "exposedParts", "consumedTokens", "examples"];
const memberKey = (entry) => (typeof entry === "string" ? entry : (entry?.name ?? entry?.id ?? null));

function run(cmd, args, cwd) {
	return execFileSync(cmd, args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], shell: process.platform === "win32" });
}

const compare = (a, b) => {
	const [x, y] = [a, b].map((v) => v.split(".").map(Number));
	for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return x[i] - y[i];
	return 0;
};

const current = JSON.parse(readFileSync(join(CORE, "package.json"), "utf8")).version;
const published = JSON.parse(run("npm", ["view", "@xtyle/core", "versions", "--json"], ROOT))
	.filter((v) => /^\d+\.\d+\.\d+$/.test(v) && compare(v, current) < 0)
	.sort(compare);

const since = {};
const record = (version, exports) => {
	for (const [subpath, names] of Object.entries(exports)) {
		since[subpath] ??= {};
		for (const name of names) since[subpath][name] ??= version;
	}
};

const members = {};
const recordMembers = (version, components) => {
	for (const component of components) {
		members[component.id] ??= {};
		for (const field of MEMBER_FIELDS) {
			if (!Array.isArray(component[field])) continue;
			members[component.id][field] ??= {};
			for (const entry of component[field]) {
				const key = memberKey(entry);
				if (key !== null) members[component.id][field][key] ??= version;
			}
		}
	}
};

const scratch = mkdtempSync(join(tmpdir(), "xtyle-api-since-"));
try {
	for (const version of published) {
		const project = join(scratch, version);
		mkdirSync(project, { recursive: true });
		writeFileSync(join(project, "package.json"), JSON.stringify({ name: "api-since-probe", private: true }));
		console.log(`reading @xtyle/core@${version}`);
		run("npm", ["install", "--no-audit", "--no-fund", "--ignore-scripts", "--no-package-lock", `@xtyle/core@${version}`], project);
		const installed = join(project, "node_modules", "@xtyle", "core");
		record(version, exportsOf(installed));
		const registry = await import(pathToFileURL(join(installed, "dist", "manifest", "registry.js")).href);
		recordMembers(version, registry.listComponents());
	}
} finally {
	rmSync(scratch, { recursive: true, force: true });
}

const now = exportsOf(CORE, true);
record(current, now);

const historical = Object.fromEntries(
	Object.entries(members).map(([id, fields]) => [
		id,
		Object.fromEntries(Object.entries(fields).map(([field, keys]) => [field, Object.fromEntries(Object.entries(keys).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)))])),
	]),
);
writeFileSync(
	MEMBERS_OUT,
	`/** The first published version each manifest member appeared in, per component and field. Generated by \`scripts/build-api-since.mjs\`; a member absent here arrived after ${published.at(-1) ?? current}. */\nexport const MEMBERS_SINCE: Record<string, Record<string, Record<string, string>>> = ${JSON.stringify(historical, null, "\t")};\n\n/** The last published version the table was read from. */\nexport const MEMBERS_READ_THROUGH = ${JSON.stringify(published.at(-1) ?? null)};\n\n/** The manifest fields read member by member. */\nexport const MEMBER_FIELDS = ${JSON.stringify(MEMBER_FIELDS)} as const;\n`,
);

const pruned = {};
for (const [subpath, names] of Object.entries(now)) {
	pruned[subpath] = Object.fromEntries(names.map((name) => [name, since[subpath][name]]));
}
writeFileSync(OUT, `${JSON.stringify({ floor: published[0] ?? current, since: pruned }, null, "\t")}\n`);
console.log(`wrote ${OUT}: ${Object.values(pruned).reduce((n, m) => n + Object.keys(m).length, 0)} exports across ${Object.keys(pruned).length} subpaths`);
