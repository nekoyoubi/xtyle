import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const elements = join(root, "packages", "xtyle", "src", "elements");
const DEFINE = /define\("(xtyle-[a-z0-9-]+)",\s*([A-Za-z0-9_]+)\)/g;

export function collectTags(dir = elements) {
	const tags = [];
	for (const file of readdirSync(dir).filter((f) => f.endsWith(".ts") && !f.endsWith(".d.ts") && !f.includes(".generated."))) {
		const source = readFileSync(join(dir, file), "utf8");
		for (const [, tag, className] of source.matchAll(DEFINE)) {
			if (!new RegExp(`export (abstract )?class ${className}\\b`).test(source)) {
				throw new Error(`build-tag-map: ${file} defines ${tag} with ${className}, which it does not export`);
			}
			tags.push({ tag, className, module: `./${file.replace(/\.ts$/, ".js")}` });
		}
	}
	return tags.sort((a, b) => a.tag.localeCompare(b.tag));
}

export function renderTagMap(tags) {
	const imports = tags.map((t) => `import type { ${t.className} } from "${t.module}";`).join("\n");
	const entries = tags.map((t) => `\t\t"${t.tag}": ${t.className};`).join("\n");
	return (
		"// generated by scripts/build-tag-map.mjs: do not edit\n" +
		`${imports}\n\ndeclare global {\n\tinterface HTMLElementTagNameMap {\n${entries}\n\t}\n}\n\nexport {};\n`
	);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	const tags = collectTags();
	writeFileSync(join(elements, "tag-map.generated.ts"), renderTagMap(tags));
	console.log(`mapped ${tags.length} tags -> packages/xtyle/src/elements/tag-map.generated.ts`);
}
